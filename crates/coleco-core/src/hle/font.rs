//! ColecoRust's own character set, placed where games expect the BIOS's.
//!
//! 71 of 164 commercial titles copy the BIOS character set into VRAM, through
//! the pointers at `$006A`/`$006C` or straight from `$158B`. The HLE has to put
//! a font there, and it cannot be the BIOS's: those bitmaps are not ours to
//! ship. So this is an original design, drawn for this project: square-cornered
//! and BOLD, every stroke two pixels wide, visibly unlike the thin originals.
//!
//! The pictures below are the skeletons; [`pattern`] thickens each one by
//! doubling every set pixel to its right. Drawn thin, 34 of the 98 glyphs came
//! out bit-identical to the BIOS's (straight-stroke letters converge on a 5x7
//! grid), which is too close for a font that has to be our own; the bold face
//! is a different design. Checked against the BIOS oracle on 2026-09-27: 0 of
//! 98 glyphs identical. No unit test can repeat that, because the BIOS is not
//! in the repository; re-check by hand after changing a glyph.
//!
//! What IS kept, because it is interface rather than artwork: the character
//! codes (`$1D` copyright, `$1E`/`$1F` a superscript TM, `$20`-`$5F` ASCII,
//! `$61`-`$7A` lowercase as small capitals, `$7F` a block) and the metrics
//! (left-aligned in the 8x8 cell, rows 0-6, small capitals on rows 2-6), so a
//! game's text lands where it was laid out to land.
//!
//! Each glyph is its rows from the top, `#` set; missing rows and columns are
//! clear.

