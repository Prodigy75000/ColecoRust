/// The 8 pattern bytes of character `c`, which must be in `$1D..=$7F`: the
/// skeleton, emboldened.
pub fn pattern(c: u8) -> [u8; 8] {
    let mut out = [0u8; 8];
    for (r, row) in GLYPHS[(c - FIRST) as usize].iter().enumerate() {
        for (x, px) in row.bytes().enumerate() {
            if px == b'#' {
                out[r] |= 0x80 >> x;
            }
        }
        out[r] |= out[r] >> 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every code has a glyph, the table ends exactly where the BIOS's does
    /// (`$18A2`), no glyph is empty but the space, and every row fits the cell.
    #[test]
    fn the_table_covers_1d_to_7f_and_ends_at_18a2() {
        assert_eq!(GLYPHS.len(), 0x7f - 0x1d + 1);
        assert_eq!(BASE as usize + GLYPHS.len() * 8 - 1, 0x18a2);
        for c in FIRST..=0x7f {
            let g = GLYPHS[(c - FIRST) as usize];
            assert!(g.len() <= 8 && g.iter().all(|r| r.len() <= 8), "glyph ${c:02X} overflows");
            assert_eq!(pattern(c) == [0; 8], c == 0x20, "glyph ${c:02X}");
        }
    }

    /// The letter and digit pointers the BIOS header advertises land on 'A'
    /// and '0' in this table.
    #[test]
    fn the_header_pointers_land_on_a_and_zero() {
        assert_eq!(BASE + (b'A' - FIRST) as u16 * 8, 0x16ab);
        assert_eq!(BASE + (b'0' - FIRST) as u16 * 8, 0x1623);
    }
}
